#!/usr/bin/env python3
"""Generate SYNTHETIC coupon data from the solver, for checking the analysis chain.

    python experiments/thermal_coupon/analysis/synthetic.py --out data/synthetic/

*** READ THIS BEFORE QUOTING ANYTHING PRODUCED BY THIS FILE ***

Everything this module writes is MADE UP BY A COMPUTER. It is the forward model's own
output with noise added. It is not a measurement, it contains no information about any
real material, and it can never be evidence that the model is right about physics -
only that the calibrate -> freeze -> predict -> compare pipeline is wired up correctly
and can recover parameters it was given.

Three guards make that impossible to forget by accident:

1. every file written carries `synthetic` in its NAME;
2. every CSV starts with a `# SYNTHETIC DATA` header line;
3. every metadata sidecar sets `synthetic: true`, which `calibrate.py` prints loudly and
   which propagates into the frozen parameter file and into any comparison report.

The physical experiment has NOT been run. `VALIDATION_MATRIX.md` row M8 says so.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from coupon_model import (  # noqa: E402
    KELVIN_OFFSET,
    CouponGeometry,
    CouponParameters,
    predict_sensors,
)

SYNTHETIC_HEADER = (
    "# SYNTHETIC DATA - generated by experiments/thermal_coupon/analysis/synthetic.py "
    "from the project's own conduction solver. NOT A MEASUREMENT. Not experimental "
    "evidence. See the file's metadata sidecar (synthetic: true)."
)

# The "unknown truth" the synthetic twin test has to recover. Order-of-magnitude values
# for a printed thermoplastic coupon in still room air; they are a TEST FIXTURE, not a
# claim about any filament.
TRUTH = CouponParameters(
    conductivity_w_mk=0.22,
    specific_heat_j_kgk=1700.0,
    contact_resistance_m2k_w=1.6e-3,
    h_front_w_m2k=9.0,
    h_back_w_m2k=7.0,
    emissivity=0.90,
)

GEOMETRY = CouponGeometry(
    thickness_m=0.010,
    density_kg_m3=1180.0,
    heated_area_m2=0.060 * 0.060,
    n_cells=80,
)

SENSOR_DEPTHS_M = (0.0000, 0.0020, 0.0050, 0.0090)

T_AMBIENT_K = 295.15


def _stable_offset(name: str) -> int:
    """A per-run seed offset that is the same in every Python process.

    Python's built-in `hash()` of a str is salted per interpreter unless PYTHONHASHSEED
    is pinned, so using it here made the "seeded" synthetic data differ between runs.
    That is a nasty bug in a test fixture: it turns a deterministic regression test into
    an intermittent one, and it was caught only because a marginal assertion about a
    statistical bias started failing at random. SHA-256 has no such salt.
    """
    return int(hashlib.sha256(name.encode()).hexdigest()[:8], 16) % 10_000


def _flux_step(t: np.ndarray, amplitude: float, on_s: float) -> np.ndarray:
    return np.where(t <= on_s, amplitude, 0.0)


def _flux_ramp(t: np.ndarray, peak: float, rise_s: float, fall_s: float) -> np.ndarray:
    """Triangular pulse: linear rise then linear fall. Nothing like a step."""
    up = np.clip(t / rise_s, 0.0, 1.0)
    down = np.clip(1.0 - (t - rise_s) / fall_s, 0.0, 1.0)
    return peak * np.minimum(up, down)


def run_definitions() -> dict[str, dict[str, Any]]:
    """The synthetic run set: two calibration runs and one deliberately unseen case.

    The calibration set is chosen to break the degeneracy the protocol warns about. A
    cool-down carries no heater flux at all, so it constrains the loss coefficients
    almost alone; a step held long enough to approach steady state constrains
    conductivity through the steady depth gradient (dT/dx = q/k) and specific heat
    through the transient approach to it. Fitting only one of them would leave a
    parameter pair the data cannot separate.

    The step run is deliberately ~3.3 diffusion times long. Shortened to 900 s - about
    one diffusion time - the steady gradient never establishes, k and cp become
    degenerate with each other, and the synthetic twin recovers them ~12% low while
    recovering their ratio (the diffusivity) to 0.4%. That is recorded in
    `docs/negative_results.md` NR-11 because it is a trap the physical protocol has to
    avoid, not an implementation detail.

    Contact resistance is a separate problem and is NOT solved by this run set. With a
    PRESCRIBED heater flux it only enters the model through the surface loss term, so it
    is weakly identifiable from these runs at any duration. `protocol.md` therefore has
    a dedicated contact-resistance characterisation step, and the calibration is run
    with it held fixed.

    The blind case is a TRIANGULAR pulse of different peak and different duration - a
    shape the calibration never showed the fit. That is the whole point of section 47:
    if the calibration absorbed a modelling error into an 'effective' parameter, a
    different pulse shape is where it surfaces.
    """
    return {
        "CAL-COOLDOWN": {
            "run_type": "calibration_cooldown",
            "duration_s": 1200.0,
            "n_samples": 1201,
            "t_initial_k": 348.15,
            "flux": lambda t: np.zeros_like(t),
            "note": "coupon pre-heated then left to cool; constrains the loss coefficients",
        },
        "CAL-STEP": {
            "run_type": "calibration_step",
            "duration_s": 3000.0,
            "n_samples": 3001,
            "t_initial_k": 295.15,
            "flux": lambda t: _flux_step(t, 1600.0, 2200.0),
            "note": ("constant heater flux held long enough to approach steady state, "
                     "then off; the steady depth gradient constrains k, the approach to "
                     "it constrains alpha and hence cp"),
        },
        "BLIND-RAMP": {
            "run_type": "blind_validation",
            "duration_s": 1500.0,
            "n_samples": 1501,
            "t_initial_k": 295.15,
            "flux": lambda t: _flux_ramp(t, 2600.0, 200.0, 500.0),
            "note": "UNSEEN heating history: triangular pulse, higher peak, shorter",
        },
    }


def generate_run(
    name: str,
    spec: dict[str, Any],
    *,
    params: CouponParameters = TRUTH,
    geometry: CouponGeometry = GEOMETRY,
    sensor_depths_m: tuple[float, ...] = SENSOR_DEPTHS_M,
    noise_k: float = 0.5,
    seed: int = 20260920,
) -> dict[str, Any]:
    """Forward-model one run and add seeded Gaussian sensor noise.

    `noise_k` = 0.5 K is the order of a well-installed type-K thermocouple with a
    two-point calibration. The seed is fixed so the synthetic twin test is deterministic
    across machines and reruns.
    """
    t = np.linspace(0.0, spec["duration_s"], spec["n_samples"])
    flux = np.asarray(spec["flux"](t), dtype=float)
    clean = predict_sensors(geometry, params, t, flux, np.array(sensor_depths_m),
                            t_initial_k=spec["t_initial_k"], t_ambient_k=T_AMBIENT_K)
    rng = np.random.default_rng(seed + _stable_offset(name))
    noisy = clean + rng.normal(0.0, noise_k, clean.shape)
    return {"name": name, "spec": spec, "time_s": t, "flux_w_m2": flux,
            "clean_k": clean, "noisy_k": noisy, "noise_k": noise_k,
            "geometry": geometry, "sensor_depths_m": np.array(sensor_depths_m)}


def write_run(run: dict[str, Any], out_dir: str | Path) -> tuple[Path, Path]:
    """Write `<name>_synthetic.csv` plus `<name>_synthetic.meta.yaml`. Returns both paths.

    The filename carries `synthetic` because a file gets copied out of its directory and
    loses its context; the name is the only part that travels with it.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{run['name'].lower().replace('-', '_')}_synthetic"
    csv_path = out_dir / f"{stem}.csv"
    meta_path = out_dir / f"{stem}.meta.yaml"

    channels = [f"t_ch{i + 1}_degc" for i in range(run["noisy_k"].shape[1])]
    header = ["time_s", "heater_flux_w_m2", *channels, "t_ambient_degc", "quality_flag"]
    lines = [SYNTHETIC_HEADER, ",".join(header)]
    for j, t in enumerate(run["time_s"]):
        cells = [f"{t:.4f}", f"{run['flux_w_m2'][j]:.6g}"]
        cells += [f"{run['noisy_k'][j, i] - KELVIN_OFFSET:.4f}" for i in range(len(channels))]
        cells += [f"{T_AMBIENT_K - KELVIN_OFFSET:.4f}", "0"]
        lines.append(",".join(cells))
    csv_path.write_text("\n".join(lines) + "\n")

    geom = run["geometry"]
    meta = {
        "schema_version": 1,
        "run_id": run["name"],
        "run_type": run["spec"]["run_type"],
        "synthetic": True,
        "synthetic_note": (
            "Generated from the project's own 1-D conduction solver with seeded Gaussian "
            "noise. NOT A MEASUREMENT. Software check only."
        ),
        "utc_generated": datetime.now(UTC).isoformat(timespec="seconds"),
        "operator": "synthetic.py",
        "notes": run["spec"]["note"],
        "coupon": {
            "material": "SYNTHETIC - no real material",
            "thickness_m": geom.thickness_m,
            "density_kg_m3": geom.density_kg_m3,
            "measured_dimensions_m": [0.060, 0.060, geom.thickness_m],
        },
        "heater": {
            "type": "SYNTHETIC - ideal zero-thermal-mass film",
            "heated_area_m2": geom.heated_area_m2,
            "flux_source": "prescribed",
            "flux_uncertainty_w_m2": 0.0,
        },
        "sensors": [
            {"channel": f"t_ch{i + 1}_degc",
             "type": "SYNTHETIC",
             "depth_m": float(d),
             "depth_uncertainty_m": 0.0,
             "temperature_uncertainty_k": run["noise_k"]}
            for i, d in enumerate(run["sensor_depths_m"])
        ],
        "sampling": {"rate_hz": float((len(run["time_s"]) - 1) / run["time_s"][-1])},
        "ambient": {"t_ambient_k": T_AMBIENT_K},
    }
    meta_path.write_text(yaml.safe_dump(meta, sort_keys=False))
    return csv_path, meta_path


def write_all(out_dir: str | Path, **kwargs) -> dict[str, tuple[Path, Path]]:
    """Generate and write every defined run. Returns {run name: (csv, meta)}."""
    return {name: write_run(generate_run(name, spec, **kwargs), out_dir)
            for name, spec in run_definitions().items()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--noise-k", type=float, default=0.5)
    ap.add_argument("--seed", type=int, default=20260920)
    args = ap.parse_args(argv)

    print("*** GENERATING SYNTHETIC DATA - NOT A MEASUREMENT ***")
    written = write_all(args.out, noise_k=args.noise_k, seed=args.seed)
    for name, (csv_path, meta_path) in written.items():
        print(f"  {name:<14} -> {csv_path.name}  +  {meta_path.name}")
    print("\nTruth parameters used to generate these files:")
    for key, value in TRUTH.to_dict().items():
        print(f"  {key:<28} {value:g}")
    print("\nA calibration run against these files should recover those numbers. That is "
          "a check on the software, not on the physics.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
