def _f(value: Any, fmt: str = ".4g") -> str:
    if value is None:
        return "—"
    try:
        x = float(value)
    except (TypeError, ValueError):
        return str(value)
    return "—" if not np.isfinite(x) else format(x, fmt)


def _pct(value: Any, digits: int = 1) -> str:
    if value is None:
        return "—"
    try:
        x = float(value)
    except (TypeError, ValueError):
        return str(value)
    return "—" if not np.isfinite(x) else f"{x * 100:.{digits}f}%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


