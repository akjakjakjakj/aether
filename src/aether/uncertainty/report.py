"""The M7 milestone report, generated entirely from a run's `summary.json`.

Every sentence that makes a claim about a number computes it here from the summary. There
is no prose in this file that asserts a result: the adjectives ("dominates", "negligible",
"within tolerance") are all produced by comparisons against thresholds declared in
`configs/uncertainty.yaml`, so re-running the study rewrites the verdicts rather than
leaving them behind as stale text.

Sections that have no result yet print what is missing and why, and do not print a table
of blanks that could be mistaken for measurements.
"""

from __future__ import annotations

